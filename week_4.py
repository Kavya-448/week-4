from google import genai
from google.colab import userdata

try:
    # Load Gemini API key
    api_key = userdata.get("GEMINI_API_KEY")

    if not api_key:
        raise ValueError("GEMINI_API_KEY not found")

    client = genai.Client(api_key=api_key)

    print("Environment ready. Starting prompt diagnosis...")

    # Function to send prompts to Gemini
    def run_prompt(prompt):
        response = client.models.generate_content(
            model="gemini-flash-lite-latest",
            contents=prompt,
            config={"temperature": 0.3}
        )
        return response.text

    # Define test cases
    cases = [
        {
            "name": "CASE 1: HALLUCINATION",
            "original": "Who won the FIFA World Cup in 1942?",
            "diagnosis": (
                "Failure type: Potential hallucination.\n"
                "Cause: The question assumes a tournament occurred "
                "in 1942, but it was cancelled due to World War II."
            ),
            "corrected": (
                "The FIFA World Cup was not held in 1942 because "
                "of World War II. Which country won the previous "
                "tournament in 1938?"
            )
        },
        {
            "name": "CASE 2: FORMAT CONSTRAINT",
            "original": (
                "List the three largest oceans on Earth. "
                "Respond using exactly three bullet points, "
                "each on a new line starting with a dash."
            ),
            "diagnosis": (
                "Failure type: Possible instruction or format failure.\n"
                "Cause: The model may not follow the exact bullet "
                "format consistently."
            ),
            "corrected": (
                "List the three largest oceans by area. Output "
                "exactly three lines. Each line must start with "
                "a dash followed by one ocean name. Do not add "
                "an introduction or conclusion."
            )
        },
        {
            "name": "CASE 3: OVER-REFUSAL",
            "original": (
                "Tell me a fun fact about the Roman Empire "
                "that is appropriate for school children."
            ),
            "diagnosis": (
                "Failure type: Potential over-refusal.\n"
                "Cause: A model may mistakenly refuse a harmless "
                "educational history request."
            ),
            "corrected": (
                "Give one harmless, historically accurate fun fact "
                "about daily life in the Roman Empire for school "
                "children. Use one simple sentence."
            )
        }
    ]

    # Run original and corrected prompts
    for case in cases:
        print("\n" + "=" * 50)
        print(case["name"])
        print("=" * 50)

        print("\nOriginal prompt:")
        print(case["original"])

        try:
            original_response = run_prompt(case["original"])
            print("\nOriginal response:")
            print(original_response)
        except Exception as e:
            original_response = None
            print("\nOriginal API error:", e)

        print("\nDiagnosis:")
        print(case["diagnosis"])

        print("\nCorrected prompt:")
        print(case["corrected"])

        try:
            corrected_response = run_prompt(case["corrected"])
            print("\nImproved response:")
            print(corrected_response)
        except Exception as e:
            print("\nCorrected API error:", e)

    print("\n" + "=" * 50)
    print("FINAL SUMMARY")
    print("=" * 50)
    print("1. Avoid assumptions about events that never happened.")
    print("2. State output formatting requirements clearly.")
    print("3. Keep harmless educational requests specific.")
    print("4. Check actual responses before declaring a failure fixed.")

except ValueError as e:
    print("Error:", e)

except Exception as e:
    print("API/Network Error:", e)